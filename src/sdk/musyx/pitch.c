u16 sndPitchUpOne(u16 pitch)
{
    return 1.05946314f * pitch;
}
u32 sndGetPitch(u8 key, u32 sample)
{
    f32 pitch;
    f32 factor;
    u8 base;
    if (sample == 0xFFFFFFFF)
        sample = 0x40005622;
    base = sample >> 24;
    if (key != base) {
        if (base < key)
            factor = toneup_tab[key - base];
        else
            factor = tonedown_tab[base - key];
        pitch = (sample & 0xFFFFFF) * factor;
    } else {
        pitch = sample & 0xFFFFFF;
    }
    return 4096.0f * pitch / synthInfo.mixFrq;
}
